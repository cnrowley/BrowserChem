/**
 * model-registry.js
 *
 * Reads model/registry.json — the catalog of available Chemprop models
 * (dataset provenance, size, metrics, hyperparameters) — and provides
 * the load-on-demand path the GNN panel UI uses. This file only ever
 * fetches registry.json itself up front; it does NOT fetch any model's
 * manifest.json/weights.bin until CC.GNN.loadRegistryModel(id) is called
 * for that specific model (see the "load on demand vs. load all" design
 * discussion this project settled on — ~10 models' worth of weights is
 * 10-15MB+ nobody should pay for before drawing a single structure).
 *
 * Split deliberately from chemprop-model.js: that file's manifest.json is
 * auto-generated by convert_chemprop_checkpoint.py every time a
 * checkpoint is exported and should never be hand-edited. registry.json
 * is the opposite — hand-authored (or authored by Claude from whatever
 * dataset/metrics info you provide per model), and never touched by the
 * conversion script. Keeping them separate means re-exporting a
 * checkpoint can never accidentally clobber its own provenance metadata.
 *
 * registry.json schema (see validate_registry.py for the authoritative
 * version of these rules):
 *   {
 *     "schemaVersion": 1,
 *     "models": [
 *       {
 *         "id": "...",              required, unique, used as the
 *                                   model key in whichever engine loads it
 *         "displayName": "...",     required
 *         "propertyKey": "...",     required (should match the
 *                                   checkpoint's own manifest.task, but
 *                                   not force-checked at load time --
 *                                   validate_registry.py checks it offline)
 *         "engine": "chemprop" | "nagl",  optional, defaults to "chemprop"
 *                                   for backward compatibility. Decides
 *                                   which loader/predictor
 *                                   (chemprop-model.js vs nagl-model.js)
 *                                   this entry's files get handed to --
 *                                   the two are genuinely different
 *                                   architectures/manifest shapes, not
 *                                   just different weights.
 *         "taskType": "regression" | "classification",  required for
 *                      "chemprop" entries; ignored for "nagl" (NAGL-MBIS
 *                      is always atom-level regression by construction)
 *         "files": { "manifest": "...", "weights": "..." },  required,
 *                   paths resolved relative to registry.json's own URL
 *         "units": "...",           optional
 *         "description": "...",     optional
 *         "dataset": { "name", "citationKey", "size", "positiveCount",
 *                      "splitStrategy", "sourceUrl" },   optional, all
 *                      sub-fields optional too -- show what you have
 *         "metrics": { "testSetSize", "primary": {"name","value"}, "all": {...} },  optional
 *         "training": { "chempropVersion", "hyperparameters", "dateTrained" },  optional
 *         "notes": "...",            optional
 *         "tags": ["..."]            optional
 *       }
 *     ]
 *   }
 *
 * A malformed individual entry is skipped with a console warning rather
 * than breaking the whole registry -- one bad hand-edited entry
 * shouldn't take down every other model's availability.
 */

window.CC = window.CC || {};
CC.GNN = window.CC.GNN || {};

(function () {
  let entries = [];       // validated registry entries, in file order
  let entriesById = new Map();
  let registryBaseUrl = ''; // directory registry.json was fetched from, for resolving relative file paths
  const loadedIds = new Set(); // which registry entries have had their weights loaded (mirrors chemprop-model.js's state, tracked here too so the UI doesn't need to poll it)

  function resolveUrl(base, relative) {
    try {
      return new URL(relative, base).href;
    } catch (err) {
      // base might itself be relative (e.g. 'model/registry.json' with no
      // scheme) -- new URL() needs an absolute base, so fall back to
      // resolving against the page's own location.
      return new URL(relative, window.location.href).href;
    }
  }

  function validateEntry(raw, index) {
    const problems = [];
    if (!raw || typeof raw !== 'object') problems.push('not an object');
    else {
      if (!raw.id) problems.push('missing "id"');
      if (!raw.displayName) problems.push('missing "displayName"');
      if (!raw.propertyKey) problems.push('missing "propertyKey"');
      const engine = raw.engine || 'chemprop';
      if (engine !== 'chemprop' && engine !== 'nagl') {
        problems.push('"engine" must be "chemprop" or "nagl", got ' + JSON.stringify(raw.engine));
      }
      if (engine === 'chemprop' && raw.taskType !== 'regression' && raw.taskType !== 'classification') {
        problems.push('"taskType" must be "regression" or "classification", got ' + JSON.stringify(raw.taskType));
      }
      if (!raw.files || !raw.files.manifest || !raw.files.weights) {
        problems.push('missing "files.manifest" / "files.weights"');
      }
      if (raw.id && entriesById.has(raw.id)) problems.push('duplicate id "' + raw.id + '"');
    }
    if (problems.length > 0) {
      console.warn('[ChemCanvas] registry.json entry #' + index + ' skipped: ' + problems.join('; '), raw);
      return null;
    }
    return raw;
  }

  /**
   * Fetch and parse registry.json. Returns a Promise resolving to the
   * validated entry list. Safe to call once at startup; individual
   * models' weights are NOT fetched here.
   */
  CC.GNN.loadModelRegistry = function (registryUrl) {
    registryBaseUrl = resolveUrl(window.location.href, registryUrl);
    return fetch(registryUrl).then(function (r) {
      if (!r.ok) throw new Error('failed to fetch registry: ' + r.status);
      return r.json();
    }).then(function (data) {
      entries = [];
      entriesById = new Map();
      (data.models || []).forEach(function (raw, i) {
        const valid = validateEntry(raw, i);
        if (valid) {
          entries.push(valid);
          entriesById.set(valid.id, valid);
        }
      });
      return entries.slice();
    });
  };

  CC.GNN.getRegistryEntries = function () { return entries.slice(); };
  CC.GNN.getRegistryEntry = function (id) { return entriesById.get(id) || null; };
  CC.GNN.isRegistryModelLoaded = function (id) { return loadedIds.has(id); };

  /**
   * Fetch and load one registry model's weights by id (paths in the
   * entry are resolved relative to registry.json's own URL). Returns a
   * Promise resolving to the same info object the underlying engine's
   * own loadXModel would (chemprop-model.js's loadChempropModel or
   * nagl-model.js's loadModel, depending on the entry's "engine" field).
   */
  CC.GNN.loadRegistryModel = function (id) {
    const entry = entriesById.get(id);
    if (!entry) return Promise.reject(new Error('No registry entry with id "' + id + '"'));

    const manifestUrl = resolveUrl(registryBaseUrl, entry.files.manifest);
    const weightsUrl = resolveUrl(registryBaseUrl, entry.files.weights);
    const engine = entry.engine || 'chemprop';

    const loadPromise = engine === 'nagl'
      ? CC.NAGL.loadModel(id, manifestUrl, weightsUrl)
      : CC.GNN.loadChempropModel(id, manifestUrl, weightsUrl);

    return loadPromise.then(function (info) {
      loadedIds.add(id);
      return info;
    });
  };

  CC.GNN.unloadRegistryModel = function (id) {
    const entry = entriesById.get(id);
    const engine = entry ? (entry.engine || 'chemprop') : 'chemprop';
    if (engine === 'nagl') CC.NAGL.clearModel(id);
    else CC.GNN.clearChempropModel(id);
    loadedIds.delete(id);
  };
})();
